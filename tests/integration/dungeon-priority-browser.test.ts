import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startWorldStudio } from '../../scripts/world-studio-server';
import { newWorldDocument } from '../../shared/world-schema';
import { newDungeonInterior } from '../../shared/warps';
import { INSTALLED_DUNGEON_DEFINITIONS } from '../../shared/dungeons';
import customDungeons from '../../shared/custom-dungeons.json';
import { newDungeonDraft } from '../../shared/dungeon-draft';

test('Dungeon Maker groups tools, shows errors above the map and shares passage authoring', { timeout: 60_000 }, async () => {
  const dir = await mkdtemp(join(tmpdir(), 'riftlands-dungeon-priority-'));
  const options = { root: resolve('.'), documentPath: join(dir, 'world.json'), dungeonPath: join(dir, 'dungeons.json'), dataPath: join(dir, 'accounts.json'), port: 0 };
  const dungeon = INSTALLED_DUNGEON_DEFINITIONS[0], project = newWorldDocument();
  project.interiors = [newDungeonInterior('test-dungeon', dungeon)];
  await writeFile(options.documentPath, JSON.stringify(project)); await writeFile(options.dungeonPath, JSON.stringify(customDungeons));
  const studio = await startWorldStudio(options); let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } }); const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    const draft = newDungeonDraft(); draft.id = dungeon.id;
    await page.addInitScript(d => localStorage.setItem('riftlands.dungeon-draft.v2', JSON.stringify(d)), draft);
    await page.goto(studio.url.replace('world-maker.html', 'dungeon-maker.html'));
    await expect(page.locator('.canvas-toolbar [data-tool="select"]')).toBeVisible();
    await expect(page.locator('.canvas-toolbar [data-tool="erase"]')).toHaveText('⌫ Cancella');
    await expect(page.locator('#dungeon-section-costruisci #terrain')).toBeVisible();
    await expect(page.locator('#dungeon-section-popola #npcs')).toBeVisible();
    await expect(page.locator('#dungeon-section-boss #bosses')).toBeVisible();
    await expect(page.locator('#dungeon-validation-alert')).toBeVisible();
    await page.locator('[data-tool="npc:old-fisher"]').click();
    const dungeonBox = (await page.locator('#map').boundingBox())!;
    await page.mouse.click(dungeonBox.x + dungeonBox.width / 2, dungeonBox.y + dungeonBox.height / 2);
    await expect(page.locator('#selected-npc-name')).toBeVisible();
    await page.locator('#selected-npc-name').fill('Pescatore locale');
    await page.locator('#update-npc-properties').click();
    await expect(page.locator('#entity-label')).toHaveValue('Pescatore locale');
    await page.locator('#selected-npc-speed').evaluate((node: HTMLInputElement) => { node.closest('details')!.open = true; });
    await page.locator('#selected-npc-speed').fill('0'); await page.locator('#update-npc-properties').click();
    await expect(page.locator('#selected-npc-speed')).toHaveValue('0');
    await page.locator('#open-passages').click();
    const frame = page.frameLocator('#dungeon-passages-frame');
    await expect(frame.locator('#surface-map')).toHaveValue('test-dungeon');
    await expect(frame.locator('#warp-tool')).toBeVisible(); await expect(frame.locator('#warp-oneway-tool')).toBeVisible();
    await frame.locator('#warp-destination').selectOption('test-dungeon');
    await frame.locator('#warp-tool').click();
    const box = (await frame.locator('#map').boundingBox())!;
    await page.mouse.click(box.x + box.width / 2 + 12, box.y + box.height / 2 + 12);
    await page.mouse.click(box.x + box.width / 2 + 12, box.y + box.height / 2 + 36);
    await expect(frame.locator('#warp-requires-key')).toBeVisible();
    await frame.locator('#warp-requires-key').check();
    await expect(frame.locator('#warp-key-place')).toBeVisible();
    await frame.locator('#warp-key-place').click();
    await expect(frame.locator('#tool-label')).toHaveText('Chiave');
    await page.mouse.click(box.x + box.width / 2 + 12, box.y + box.height / 2 + 60);
    await expect(frame.locator('#tool-label')).toHaveText('Seleziona');
    await page.locator('#close-passages').click(); await expect(page.locator('#dungeon-passages-dialog')).not.toBeVisible();
    const worldPage = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
    await worldPage.goto(studio.url); await expect(worldPage.locator('#status')).not.toContainText('Caricamento');
    await worldPage.locator('#npc').selectOption('old-fisher'); await worldPage.locator('[data-tool="npc"]').click();
    const worldBox = (await worldPage.locator('#map').boundingBox())!;
    await worldPage.mouse.click(worldBox.x + worldBox.width / 2 + 12, worldBox.y + worldBox.height / 2 + 12);
    await worldPage.locator('[data-tool="select"]').click();
    await worldPage.mouse.click(worldBox.x + worldBox.width / 2 + 12, worldBox.y + worldBox.height / 2 + 12);
    await expect(worldPage.locator('#selected-npc-name')).toBeVisible();
    await worldPage.locator('#selected-npc-name').fill('Pescatore nel mondo'); await worldPage.locator('#selection-update').click();
    await expect(worldPage.locator('#selected-npc-name')).toHaveValue('Pescatore nel mondo');
    await worldPage.close();
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await studio.close(); await rm(dir, { recursive: true, force: true }); }
});
