import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startWorldStudio } from '../../scripts/world-studio-server';
import { newWorldDocument, parseWorldDocument } from '../../shared/world-schema';
import { WorldAuthoring } from '../../shared/world-authoring';

test('decimal climate bands support add/remove, separate curves, preview, undo and project persistence', { timeout: 90_000 }, async () => {
  const fixture = newWorldDocument(42);
  fixture.zones.push({ id: 'target', name: 'Bande clima', priority: 1, shape: { kind: 'circle', x: 0, y: 0, radius: 10 }, temperature: .1, moisture: .8, climateTransition: 1 });
  for (let y = -20; y <= 20; y++) for (let x = -20; x <= 20; x++) fixture.tiles.push({ x, y, terrain: 'grass', suppressAssets: true });
  const directory = await mkdtemp(join(tmpdir(), 'riftlands-climate-bands-'));
  const documentPath = join(directory, 'world.json');
  await writeFile(documentPath, JSON.stringify(fixture)); await writeFile(join(directory, 'dungeons.json'), '[]');
  const studio = await startWorldStudio({ root: resolve('.'), documentPath, dungeonPath: join(directory, 'dungeons.json'), dataPath: join(directory, 'accounts.json'), port: 0 });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } }), errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(studio.url); await expect(page.locator('#status')).toContainText('World Studio pronto');
    const selectZone = async () => {
      if (!(await page.locator('#project-settings').evaluate((d: HTMLDetailsElement) => d.open))) await page.locator('#project-settings > summary').click();
      await page.locator('#zone-list button').filter({ hasText: 'Bande clima' }).click();
      if (await page.locator('#zone-climate-settings').isHidden()) await page.locator('#zone-climate-settings-toggle').click();
    };
    const exported = async () => {
      const download = page.waitForEvent('download'); await page.locator('#export-world').click();
      await (await download).saveAs(join(directory, 'export.json'));
      return parseWorldDocument(JSON.parse(await readFile(join(directory, 'export.json'), 'utf8')).document);
    };
    await selectZone();
    for (let i = 0; i < 3; i++) await page.locator('#zone-climate-band-add-temperature').click();
    await expect(page.locator('#zone-climate-band-add-temperature')).toBeDisabled();
    await expect(page.locator('#zone-climate-simple-temperature')).toBeHidden();
    await page.locator('#zone-climate-band-temperature-0-at').fill('20');
    await page.locator('#zone-climate-band-temperature-0-value').fill('0.5');
    await page.locator('#zone-climate-band-temperature-0-curve').selectOption('1');
    await page.locator('#zone-climate-band-temperature-1-at').fill('80');
    await page.locator('#zone-climate-band-temperature-1-value').fill('0.3');
    await page.locator('#zone-climate-band-temperature-1-curve').selectOption('3');
    await page.locator('#zone-climate-band-temperature-2-value').fill('0.1');
    await page.locator('#zone-climate-band-temperature-2-curve').selectOption('1');
    await expect(page.locator('#zone-climate-band-temperature-2-at')).toHaveValue('100');
    await expect(page.locator('#zone-climate-band-temperature-2-at')).not.toBeEditable();
    await expect(page.locator('#zone-climate-curve-samples')).toContainText('0.325');
    await page.locator('#zone-climate-band-add-moisture').click();
    await page.locator('#zone-climate-band-moisture-0-value').fill('0.2');
    await page.locator('#zone-climate-band-moisture-0-curve').selectOption('0.5');
    await page.locator('[data-tool="zone"]').click();
    await expect(page.locator('#zone-climate-band-temperature-1-value')).toHaveValue('0.3');
    await expect(page.locator('#zone-climate-band-moisture-0-value')).toHaveValue('0.2');
    await page.locator('#zone-update').click();
    await expect(page.locator('#zone-temperature')).toHaveValue('0.1');
    await expect(page.locator('#zone-moisture')).toHaveValue('0.2');
    const original = await exported();
    assert.equal(original.zones[0].climateBands!.temperature!.length, 3);
    assert.equal(original.zones[0].climateBands!.moisture![0].value, .2);
    await page.locator('#zone-climate-band-remove-temperature-1').click(); await page.locator('#zone-update').click();
    const removed = (await exported()).zones[0].climateBands!.temperature!;
    assert.deepEqual(removed.map(b => [b.at, b.value]), [[.2, .5], [1, .1]]);
    await page.locator('#undo').click(); await selectZone();
    await expect(page.locator('#zone-climate-band-count-temperature')).toHaveValue('3');
    await page.locator('#redo').click(); await selectZone();
    await expect(page.locator('#zone-climate-band-count-temperature')).toHaveValue('2');
    await page.locator('#undo').click(); await selectZone();
    await page.locator('#apply-world').click(); await expect(page.locator('#status')).toContainText('Progetto salvato con backup');
    const installed = parseWorldDocument(JSON.parse(await readFile(documentPath, 'utf8')));
    assert.deepEqual(installed.zones, original.zones);
    const a = new WorldAuthoring(installed);
    assert.ok(Math.abs(a.climateAt(5, 0, 'temperature', () => 1) - .325) < 1e-10);
    assert.equal(a.climateAt(0, 0, 'temperature', () => 1), .1);
    assert.equal(a.climateAt(0, 0, 'moisture', () => 1), .2);
    await page.reload(); await expect(page.locator('#status')).toContainText('World Studio pronto'); await selectZone();
    await expect(page.locator('#zone-climate-band-count-temperature')).toHaveValue('3');
    await expect(page.locator('#zone-climate-band-temperature-1-value')).toHaveValue('0.3');
    // Incomplete input must not prevent deleting a band.
    await page.locator('#zone-climate-band-temperature-1-value').fill('');
    await page.locator('#zone-climate-band-remove-temperature-1').click();
    await expect(page.locator('#zone-climate-band-count-temperature')).toHaveValue('2');
    await page.locator('#zone-climate-band-remove-temperature-1').click();
    await page.locator('#zone-climate-band-remove-temperature-0').click();
    await expect(page.locator('#zone-climate-simple-temperature')).toBeVisible();
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await studio.close(); await rm(directory, { recursive: true, force: true }); }
});
