import test from 'node:test';
import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startWorldStudio } from '../../scripts/world-studio-server';
import { newWorldAsset, newWorldDocument } from '../../shared/world-schema';
import { newInterior } from '../../shared/warps';

test('removing instances preserves the catalog; permanent deletion removes the file after confirmation', { timeout: 90_000 }, async () => {
  const root = resolve('.');
  await mkdir(join(root, 'artifacts'), { recursive: true });
  const directory = await mkdtemp(join(root, 'artifacts/asset-deletion-'));
  const options = { root: directory, port: 0, documentPath: join(directory, 'world.json'), dungeonPath: join(directory, 'dungeons.json'), dataPath: join(directory, 'accounts.json') };
  const document = newWorldDocument();
  document.assets.push(newWorldAsset('tree', 'Albero', '/world-assets/tree.svg'), newWorldAsset('keep', 'Pietra', '/world-assets/keep.svg'));
  document.assets.push(newWorldAsset('duplicate', 'Cespuglio v0 di prova', '/world-assets/tree.svg'));
  document.placements.push({ id: 'one', assetId: 'tree', x: 4, y: 4 }, { id: 'two', assetId: 'keep', x: 7, y: 7 });
  const interior = newInterior('house', 'Casa', 8, 8);
  interior.document.placements.push({ id: 'inside', assetId: 'tree', x: 2, y: 2 });
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) interior.document.tiles.push({ x, y, terrain: 'grass', suppressAssets: true });
  document.interiors = [interior];
  for (let y = -2; y <= 10; y++) for (let x = -2; x <= 10; x++) document.tiles.push({ x, y, terrain: 'grass', suppressAssets: true });
  await Promise.all([cp(join(root, 'client'), join(directory, 'client'), { recursive: true }), cp(join(root, 'shared'), join(directory, 'shared'), { recursive: true }),
    cp(join(root, 'world-maker.html'), join(directory, 'world-maker.html')), mkdir(join(directory, 'public/world-assets'), { recursive: true }),
    writeFile(options.documentPath, JSON.stringify(document)), writeFile(options.dungeonPath, '[]')]);
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48"><rect width="48" height="48" fill="green"/></svg>';
  await writeFile(join(directory, 'public/world-assets/tree.svg'), svg); await writeFile(join(directory, 'public/world-assets/keep.svg'), svg);
  const studio = await startWorldStudio(options);
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } }), errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(studio.url); await expect(page.locator('#status')).toContainText('World Studio pronto');
    await page.locator('#asset-list [data-asset="tree"]').click();
    await page.locator('#asset-delete').click();
    await expect(page.locator('#asset-list [data-asset="tree"]')).toHaveCount(1);
    await page.locator('#apply-world').click(); await expect(page.locator('#status')).toContainText('Progetto applicato');
    let saved = JSON.parse(await readFile(options.documentPath, 'utf8'));
    assert.equal(saved.assets.length, 3); assert.deepEqual(saved.placements.map((p: { assetId: string }) => p.assetId), ['keep']);
    assert.equal(saved.interiors[0].document.placements.length, 0);
    assert.equal(await readFile(join(directory, 'public/world-assets/tree.svg'), 'utf8'), svg);
    await page.locator('#undo').click();
    await page.locator('#apply-world').click(); await expect(page.locator('#status')).toContainText('Progetto applicato');
    saved = JSON.parse(await readFile(options.documentPath, 'utf8')); assert.equal(saved.placements.length, 2);
    assert.equal(saved.interiors[0].document.placements.length, 1);
    await page.locator('#asset-list [data-asset="duplicate"]').click();
    await expect(page.locator('#asset-image-usage')).toContainText('Albero (tree)');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#asset-delete-permanently').click();
    await expect(page.locator('#status')).toContainText('asset “Albero” (tree)');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#asset-remove-catalog').click();
    await expect(page.locator('#asset-list [data-asset="duplicate"]')).toHaveCount(0);
    await page.locator('#undo').click();
    await expect(page.locator('#asset-list [data-asset="duplicate"]')).toHaveCount(1);
    await page.locator('#asset-list [data-asset="duplicate"]').click();
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#asset-remove-catalog').click();
    await expect(page.locator('#asset-list [data-asset="duplicate"]')).toHaveCount(0);
    assert.equal(await readFile(join(directory, 'public/world-assets/tree.svg'), 'utf8'), svg);
    await page.locator('#asset-list [data-asset="tree"]').click();
    page.once('dialog', dialog => dialog.dismiss());
    await page.locator('#asset-delete-permanently').click();
    assert.equal(await readFile(join(directory, 'public/world-assets/tree.svg'), 'utf8'), svg);
    const endpoint = new URL('/__world/delete-asset', studio.url);
    const denied = await fetch(endpoint, { method: 'POST', headers: { Origin: endpoint.origin, 'Content-Type': 'application/json' }, body: '{}' });
    assert.equal(denied.status, 403);
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#asset-delete-permanently').click();
    await expect(page.locator('#status')).toContainText('eliminati definitivamente');
    await expect(page.locator('#undo')).toBeDisabled();
    saved = JSON.parse(await readFile(options.documentPath, 'utf8'));
    assert.deepEqual(saved.assets.map((a: { id: string }) => a.id), ['keep']);
    assert.deepEqual(saved.placements.map((p: { assetId: string }) => p.assetId), ['keep']);
    assert.equal(saved.interiors[0].document.placements.length, 0);
    await assert.rejects(readFile(join(directory, 'public/world-assets/tree.svg')), { code: 'ENOENT' });
    assert.equal(await readFile(join(directory, 'public/world-assets/keep.svg'), 'utf8'), svg);
    await page.reload(); await expect(page.locator('#status')).toContainText('World Studio pronto');
    await expect(page.locator('#asset-list [data-asset="tree"]')).toHaveCount(0);
    await page.locator('#asset-catalog-expand').click();
    await page.locator('#asset-catalog-pin').click();
    await page.locator('#asset-list [data-asset="keep"]').click();
    await expect(page.locator('#asset-catalog-dialog')).toBeVisible();
    await expect(page.locator('#asset-name')).toHaveValue('Pietra');
    await page.locator('#inspector-enlarge').click();
    const catalogBox = (await page.locator('#asset-catalog-dialog').boundingBox())!, inspectorBox = (await page.locator('.inspector').boundingBox())!;
    assert.ok(catalogBox.x + catalogBox.width <= inspectorBox.x);
    await page.screenshot({ path: join(root, 'artifacts/asset-panels-review.png') });
    await page.reload(); await expect(page.locator('#status')).toContainText('World Studio pronto');
    await expect(page.locator('#asset-catalog-dialog')).toBeVisible();
    await expect(page.locator('.inspector')).toHaveClass(/dock-expanded/);
    await page.locator('#asset-list [data-asset="keep"]').click();
    await expect(page.locator('#asset-catalog-dialog')).toBeVisible();
    await page.locator('#asset-catalog-pin').click();
    await page.locator('#asset-list [data-asset="keep"]').click();
    await expect(page.locator('#asset-catalog-dialog')).not.toBeVisible();
    await page.locator('#workspace-reset').click();
    await expect(page.locator('.inspector')).not.toHaveClass(/dock-expanded/);
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await studio.close(); await rm(directory, { recursive: true, force: true }); }
});
