test('local Studio manages authored dungeons in the browser and refuses unauthorized or concurrent writes', { timeout: 60_000 }, async () => {
    const directory = await mkdtemp(join(tmpdir(), 'riftlands-studio-'));
    const options = { root: resolve('.'), port: 0, catalogPath: join(directory, 'catalog.json'), dataPath: join(directory, 'accounts.json') };
    await writeFile(options.catalogPath, '[]');
    await writeFile(`${options.catalogPath}.old.bak`,'[]');
    await writeFile(options.dataPath, JSON.stringify({ version: 2, accounts: [{ id: 'preserve', gold: 50 }], bosses: {} }));
    const studio = await startDungeonStudio(options);
    let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
    try {
        browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL ?? 'chrome', headless: true });
        const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
        const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
        page.on('dialog', dialog => dialog.accept());
        await page.addInitScript(draft => {
            if (!localStorage.getItem('riftlands.dungeon-draft.v2')) localStorage.setItem('riftlands.dungeon-draft.v2', JSON.stringify(draft));
        }, studioDraft());
        await page.goto(studio.url);
        await expect(page.locator('#dungeon-library')).toBeVisible();
        await page.locator('[data-action="install"]').click();
        await expect(page.locator('#dungeon-library option')).toHaveCount(1);
        await page.locator('[data-library="open"]').click();
        await expect(page.locator('#map-id')).toHaveValue('studio-test');
        const box=(await page.locator('#map').boundingBox())!;
        const scale=Math.max(4,Math.min(46,(box.width-60)/24,(box.height-60)/18));
        const tile=(x:number,y:number)=>({x:box.x+(box.width-24*scale)/2+(x+.5)*scale,y:box.y+(box.height-18*scale)/2+(y+.5)*scale});
        await page.locator('[data-tool="select"]').click();
        const boss=tile(12,9); await page.mouse.click(boss.x,boss.y);
        await page.locator('#entity-properties').getByText('Avanzate · posizione e incontro', { exact: true }).click();
        await expect(page.locator('#entity-aggroRadius')).toBeVisible();
        await page.locator('#entity-aggroRadius').fill('432'); await page.locator('#entity-aggroRadius').press('Tab');
        await page.locator('[data-tool="activation"]').click();
        const from=tile(3,5),to=tile(10,5);
        await page.mouse.move(from.x,from.y); await page.mouse.down();
        await page.mouse.move(to.x,to.y,{steps:14}); await page.mouse.up();
        await page.locator('[data-tool="visitors"]').click();
        const blueStart=tile(3,7),blueEnd=tile(8,7);
        await page.mouse.move(blueStart.x,blueStart.y);await page.mouse.down();await page.mouse.move(blueEnd.x,blueEnd.y,{steps:1});await page.mouse.up();
        await page.locator('[data-tool="visitors-erase"]').click();await page.mouse.click(blueEnd.x,blueEnd.y);
        await page.locator('#undo').click();
        await expect(page.locator('#issues')).toHaveText('Terreno e posizioni validi.');
        await page.locator('#name').fill('Studio aggiornato'); await page.locator('#name').press('Tab');
        await page.locator('[data-action="update"]').click();
        await expect(page.locator('#dungeon-library option')).toHaveText('Studio aggiornato · studio-test');
        const installed=JSON.parse(await readFile(options.catalogPath,'utf8'))[0];
        assert.equal(installed.definition.encounter.activationPoints.length,8);
        assert.equal(installed.definition.encounter.regions.bossAggro.radius,432);
        assert.equal(installed.definition.encounter.visitorTiles.length,6);
        await page.locator('[data-library="open"]').click();
        const restored=await page.evaluate(()=>JSON.parse(localStorage.getItem('riftlands.dungeon-draft.v2')!));
        assert.equal(restored.entities.filter((e:any)=>e.kind==='activation').length,8);
        assert.equal(restored.entities.find((e:any)=>e.kind==='boss').aggroRadius,432);
        assert.equal(restored.encounters[0].visitorTiles.length,6);
        const endpoint = new URL('/__studio/library', studio.url), origin = endpoint.origin;
        const library = await (await fetch(endpoint)).json() as { token: string };
        const write = (headers: Record<string, string>) => fetch(endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify({ action: 'remove', id: 'studio-test' }) });
        assert.equal((await write({ Origin: origin })).status, 403);
        assert.equal((await write({ Origin: 'https://untrusted.example', 'X-Studio-Token': library.token })).status, 403);
        const release = acquireDataLease(options.dataPath);
        try {
            const blocked = await write({ Origin: origin, 'X-Studio-Token': library.token });
            assert.equal(blocked.status, 400);
            assert.match(await blocked.text(), /Salvataggio in uso/);
            const blockedBackups=await fetch(endpoint,{method:'POST',headers:{'Content-Type':'application/json',Origin:origin,'X-Studio-Token':library.token},body:JSON.stringify({action:'remove-backups',scope:'all'})});
            assert.equal(blockedBackups.status,400);
        } finally { release(); }
        await page.locator('[data-action="remove"]').click();
        await expect(page.locator('#dungeon-library option')).toHaveCount(0);
        await page.locator('#backup-scope').selectOption('dungeon:studio-test');
        await expect(page.locator('#backup-summary')).toContainText('6 file');
        await page.locator('#delete-backups').click();
        await expect(page.locator('#status')).toContainText('Eliminati 6 file di backup');
        assert.deepEqual((await listDungeonBackups(options)).map(g=>g.scope),['legacy']);
        await page.locator('#backup-scope').selectOption('all');
        await page.locator('#delete-backups').click();
        await expect(page.locator('#status')).toContainText('Eliminati 1 file di backup');
        await expect(page.locator('#delete-backups')).toBeDisabled();
        assert.deepEqual(await listDungeonBackups(options),[]);
        assert.deepEqual(JSON.parse(await readFile(options.catalogPath, 'utf8')), []);
        assert.deepEqual(JSON.parse(await readFile(options.dataPath, 'utf8')).accounts, [{ id: 'preserve', gold: 50 }]);
        assert.deepEqual(errors, []);
    } finally { await browser?.close(); await studio.close(); await rm(directory, { recursive: true, force: true }); }
});

test('Dungeon Maker picks visible planes, preserves raised materials and builds bridge accesses in one gesture', { timeout: 60_000 }, async () => {
    const directory = await mkdtemp(join(tmpdir(), 'riftlands-dungeon-layers-'));
    const catalogPath = join(directory, 'catalog.json'); await writeFile(catalogPath, '[]');
    const studio = await startDungeonStudio({ root: resolve('.'), port: 0, catalogPath, dataPath: join(directory, 'accounts.json') });
    let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
    try {
        browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL ?? 'chrome', headless: true });
        const page = await browser.newPage({ viewport: { width: 1700, height: 1100 } });
        const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
        await page.goto(studio.url);
        await expect(page.locator('#dungeon-surfaces')).toBeVisible();
        await page.locator('#dungeon-surfaces summary').filter({ hasText: 'Materiali e impostazioni avanzate' }).click();
        await page.locator('#fit').click();
        const box = (await page.locator('#map').boundingBox())!;
        const scale = Math.max(4, Math.min(46, (box.width - 60) / 24, (box.height - 60) / 18));
        const tile = (x: number, y: number, elevation = 0) => ({ x: box.x + (box.width - 24 * scale) / 2 + (x + .5) * scale, y: box.y + (box.height - 18 * scale) / 2 + (y + .5 - elevation / 3) * scale });
        const click = async (x: number, y: number, elevation = 0) => { const p = tile(x, y, elevation); await page.mouse.click(p.x, p.y); };
        const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('riftlands.dungeon-draft.v2')!));
        await page.locator('#dungeon-elevation').fill('2');
        await page.locator('#dungeon-surface-material').selectOption('stone');
        await page.locator('#dungeon-wall-material').selectOption('brick');
        await page.locator('[data-tool="surface-paint"]').click();
        await click(4, 4);
        await page.locator('[data-tool="surface-raise"]').click(); await click(4, 4, 2);
        let draft = await saved();
        assert.deepEqual(draft.surfaceCells.find((c: any) => c.x === 4 && c.y === 4), { x: 4, y: 4, surfaceId: 'ground', kind: 'ground', elevation: 3, material: 'stone', wallMaterial: 'brick', blocked: false });
        await page.locator('[data-tool="surface-lower"]').click(); await click(4, 4, 3);
        await page.locator('#dungeon-surface-material').selectOption('path');
        await page.locator('#dungeon-wall-material').selectOption('earth');
        await page.locator('[data-tool="surface-paint"]').click(); await click(8, 6); await click(11, 6);
        await page.locator('#dungeon-bridge-new').click();
        const from = tile(8, 6, 2), to = tile(11, 6, 2);
        await page.mouse.move(from.x, from.y); await page.mouse.down(); await page.mouse.move(to.x, to.y, { steps: 12 }); await page.mouse.up();
        draft = await saved();
        const bridgeId = draft.surfaceCells.find((c: any) => c.kind === 'bridge')?.surfaceId;
        assert.ok(bridgeId);
        assert.equal(draft.surfaceCells.find((c: any) => c.x === 4 && c.y === 4).wallMaterial, 'brick');
        assert.equal(draft.surfaceCells.find((c: any) => c.x === 4 && c.y === 4).elevation, 2);
        assert.equal(draft.surfaceCells.filter((c: any) => c.surfaceId === bridgeId).length, 2);
        assert.equal(draft.surfaceLinks.length, 2);
        assert.equal(draft.surfaceLinks[0].to.surfaceId, bridgeId);
        assert.equal(draft.tileRuns.some(([kind]: [string, number]) => kind === 'water'), false);
        await page.locator('#undo').click(); draft = await saved(); assert.equal(draft.surfaceLinks?.length ?? 0, 0); assert.equal(draft.surfaceCells.some((c: any) => c.kind === 'bridge'), false);
        await page.locator('#redo').click(); assert.equal((await saved()).surfaceLinks.length, 2);
        await page.locator('[data-tool="pickup:heal"]').click(); await click(9, 6, 2);
        await page.locator('#dungeon-show-under').check(); await click(9, 6);
        draft = await saved();
        const pickups = draft.entities.filter((e: any) => e.kind === 'pickup' && e.x === 9 && e.y === 6);
        assert.equal(pickups.length, 2); assert.equal(pickups.filter((e: any) => e.surfaceId === bridgeId).length, 1); assert.equal(pickups.filter((e: any) => !e.surfaceId).length, 1);
        await page.locator('#dungeon-show-under').uncheck();
        await page.locator('[data-tool="surface-link:stairs"]').click(); await click(8, 6, 2); await click(8, 7);
        draft = await saved(); assert.equal(draft.surfaceLinks.filter((l: any) => l.kind === 'stairs').length, 1);
        await page.locator('#dungeon-bridge-new').click(); await page.mouse.move(from.x, from.y); await page.mouse.down();
        const diagonal = tile(4, 4, 2); await page.mouse.move(diagonal.x, diagonal.y); await page.mouse.up();
        await expect(page.locator('#dungeon-surface-info')).toContainText('Allinea');
        assert.equal((await saved()).surfaceCells.filter((c: any) => c.kind === 'bridge').length, 2);
        await page.keyboard.press('Escape'); await expect(page.locator('#dungeon-link-cancel')).toBeHidden();
        await page.reload(); await expect(page.locator('#dungeon-surface-id option')).toHaveCount(3);
        await page.locator('#example').selectOption('surface-demo');
        await expect(page.locator('#issues')).toHaveText('Terreno e posizioni validi.');
        draft = await saved(); assert.equal(draft.encounters.length, 0); assert.equal(draft.entities[1].surfaceId, 'bridge-demo');
        await mkdir(resolve('.tmp'), { recursive: true });
        await page.screenshot({ path: resolve('.tmp/dungeon-surfaces-maker.png') });
        await page.locator('#preview').click(); await expect(page.locator('#playtest-dialog')).toBeVisible();
        await expect(page.locator('#playtest-status')).toContainText('HP');
        await page.locator('#playtest-close').click(); assert.deepEqual(errors, []);
    } finally { await browser?.close(); await studio.close(); await rm(directory, { recursive: true, force: true }); }
});
