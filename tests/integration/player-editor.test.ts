import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { mkdtemp, writeFile, readFile, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { startWorldStudio } from '../../scripts/world-studio-server';
import { ACTOR_CATALOG } from '../../shared/actor-catalog';
import { newWorldDocument } from '../../shared/world-schema';

test('shared character editor persists player sheets, shadows and attacks and renders locomotion rules', { timeout: 60_000 }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'riftlands-player-editor-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const root = resolve('.'), options = { root, documentPath: join(dir, 'world.json'), dungeonPath: join(dir, 'dungeons.json'), dataPath: join(dir, 'accounts.json'), port: 0 };
  const path = join(dir, 'actor-catalog.json');
  await writeFile(options.documentPath, JSON.stringify(newWorldDocument())); await writeFile(options.dungeonPath, '[]'); const initial = structuredClone(ACTOR_CATALOG); delete initial.playerSkins; await writeFile(path, JSON.stringify(initial));
  const studio = await startWorldStudio(options); let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL ?? 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } }), errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(studio.url); await expect(page.locator('#status')).toContainText('World Studio pronto');
    await page.locator('#open-player-editor').click(); await expect(page.locator('#boss-status')).toHaveText('Catalogo caricato.');
    await page.locator('#boss-select').selectOption('mage');
    await expect(page.locator('[data-select-slot=basic]')).toHaveText('Ranged · Dardo arcano');
    await expect(page.locator('[data-select-slot=q]')).toHaveAttribute('title', 'Ranged · Lancia di gelo');
    await page.locator('#boss-select').selectOption('warrior');
    await expect(page.locator('[data-select-slot=basic]')).toHaveText('Melee · Fendente');
    await page.locator('#boss-select').selectOption('hunter');
    await expect(page.locator('[data-select-slot=r]')).toHaveText('AoE · Tempesta di frecce');
    assert.equal(await page.locator('[data-select-slot=r]').evaluate(el => getComputedStyle(el).textOverflow), 'ellipsis');
    await expect(page.locator('[data-select-slot=r]')).toHaveAttribute('title', 'AoE · Tempesta di frecce');
    assert.ok(await page.locator('#boss-slots').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    await page.locator('#boss-select').selectOption('mage');
    await expect(page.locator('[data-slot-asset=moving]')).toHaveValue('/actor-assets/mage256.png');
    await expect(page.locator('[data-slot-asset=idle]')).toHaveValue(''); await expect(page.locator('#boss-animation-label')).toBeHidden();
    await expect(page.locator('#boss-animation-rule')).toContainText('Idle vuoto');
    await page.locator('#boss-direction').selectOption('2'); await page.locator('#boss-preview-state').selectOption('idle');
    await expect(page.locator('#boss-frame')).toContainText('Frame 9 / 16');
    await page.locator('#boss-drawSize').fill('96');
    await page.locator('#boss-shadowWidth').fill('32'); await page.locator('#boss-shadowOpacity').fill('0.45');
    await page.locator('[data-select-slot=basic]').click();
    await expect(page.locator('#boss-sheet-empty')).toContainText('Nessuna immagine');
    await expect(page.locator('#boss-sheet-settings')).toBeHidden();
    await page.locator('[data-slot-asset=basic]').selectOption('/actor-assets/mage256.png');
    await page.locator('[data-select-slot=idle]').click();
    await expect(page.locator('[data-slot-asset=idle]')).toHaveValue('');
    // Browsing empty slots never creates or clones sheets, including during save.
    await page.locator('#boss-select').selectOption('paladin');
    await page.locator('[data-slot-asset=idle]').selectOption('/actor-assets/paladino256.png');
    await page.locator('#boss-columns').fill('4'); await page.locator('#boss-columns').dispatchEvent('change');
    await page.locator('#boss-directional').check();
    await page.locator('[data-slot-asset=moving]').selectOption('');
    await expect(page.locator('#boss-animation-rule')).toContainText('Solo Idle');
    await page.locator('#boss-shadow-enabled').uncheck();
    await page.locator('[data-select-slot=basic]').click();
    await page.evaluate(() => { (window as any).__saveIdentity = 'still-open'; });
    const navigations: string[] = []; page.on('framenavigated', frame => { if (frame === page.mainFrame()) navigations.push(frame.url()); });
    await page.locator('#boss-save').click(); await expect(page.locator('#boss-status')).toContainText('Catalogo salvato con backup');
    await page.waitForTimeout(1200);
    await expect(page.locator('#boss-editor')).toBeVisible();
    await expect(page.locator('[data-select-slot=basic]')).toHaveAttribute('aria-pressed', 'true');
    assert.equal(await page.evaluate(() => (window as any).__saveIdentity), 'still-open'); assert.deepEqual(navigations, []);
    const saved = JSON.parse(await readFile(path, 'utf8'));
    const mage = saved.skins[saved.playerSkins.mage], paladin = saved.skins[saved.playerSkins.paladin];
    assert.equal(mage.drawSize, 96); assert.equal(mage.animations.idle, undefined); assert.equal(mage.animations.basic.loop, false);
    assert.deepEqual(mage.shadow, { x: 1, y: 13, width: 32, height: 8.4, opacity: .45 });
    assert.equal(paladin.shadow.opacity, 0); assert.equal(paladin.animations.moving, undefined);
    assert.deepEqual(Object.keys(paladin.animations), ['idle'], 'visiting and saving an empty attack never creates a sheet');
    assert.deepEqual(saved.bosses, ACTOR_CATALOG.bosses); assert.deepEqual(saved.npcSkins, ACTOR_CATALOG.npcSkins);
    const runtime = await page.evaluate(`(async () => {
      const { CatalogSpriteRenderer } = await import('/client/render/catalog-sprite-renderer.ts');
      const { ActorRenderer } = await import('/client/render/actor-renderer.ts');
      const sprites = new CatalogSpriteRenderer(); await sprites.prepare();
      const canvas = document.createElement('canvas'); canvas.width = canvas.height = 256;
      const ctx = canvas.getContext('2d'); ctx.translate(128,128);
      const actor = {id:'p',kind:'player',name:'',classId:'mage',x:0,y:0,radius:15,hp:100,maxHp:100,resource:100,maxResource:100,aim:0,speed:0,level:1,xp:0,kills:0,deaths:0,teamId:null,hidden:false,revealedUntil:0,deadUntil:0,spawnProtectedUntil:0,effects:[],cooldowns:{basic:0,q:0,e:0,r:0},spriteMoving:false,spriteRow:2};
      const sample = (time,moving) => {ctx.clearRect(-128,-128,256,256); sprites.drawPlayer(ctx,actor,time,moving,2); return canvas.toDataURL();};
      const idle = sample(0,false), idleLater = sample(260,false), moving = sample(130,true);
      actor.classId='paladin'; const staticIdle = sample(130,false), displaced = sample(130,true);
      const renderer = new ActorRenderer(ctx,matchMedia('(pointer: coarse)')); await renderer.spritesReady;
      const widths=[], shadows=[], originalDraw=ctx.drawImage.bind(ctx), originalEllipse=ctx.ellipse.bind(ctx);
      ctx.drawImage=(...args)=>{widths.push(args[3]); originalDraw(...args);};
      ctx.ellipse=(...args)=>{shadows.push(args.slice(0,4)); originalEllipse(...args);};
      actor.classId='mage'; renderer.drawActor(actor,0,false,false,false,new Set());
      return {still:idle===idleLater, animated:idle!==moving, idleOnly:staticIdle===displaced, widths, shadows, radius:actor.radius};
    })()`);
    assert.deepEqual(runtime, { still: true, animated: true, idleOnly: true, widths: [96], shadows: [[1,13,32,8.4]], radius: 15 });
    await page.locator('#boss-reload').click(); await expect(page.locator('#boss-status')).toHaveText('Catalogo caricato.');
    await page.locator('#boss-select').selectOption('mage'); await expect(page.locator('#boss-drawSize')).toHaveValue('96');
    await page.locator('[data-select-slot=idle]').click(); await expect(page.locator('[data-slot-asset=idle]')).toHaveValue('');
    await page.locator('[data-select-slot=moving]').click(); await page.locator('#boss-slots').scrollIntoViewIfNeeded();
    await mkdir(join(root, '.tmp'), { recursive: true }); await page.screenshot({ path: join(root, '.tmp/player-editor-desktop.png') });
    await page.setViewportSize({ width: 844, height: 390 });
    assert.ok(await page.locator('#boss-editor').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    await expect(page.locator('#boss-close')).toBeInViewport(); await page.screenshot({ path: join(root, '.tmp/player-editor-landscape.png') });
    await page.locator('#boss-close').click(); await page.locator('#open-npc-editor').click();
    await expect(page.locator('#boss-status')).toHaveText('Catalogo caricato.'); await expect(page.locator('#boss-npc-identity')).toBeVisible();
    await page.locator('#boss-select').selectOption('wisp');
    await expect(page.locator('[data-select-slot=basic]')).toHaveText('Ranged');
    await expect(page.locator('[data-select-slot=q]')).toHaveCount(0);
    await page.locator('#boss-select').selectOption('slime');
    await expect(page.locator('[data-select-slot=basic]')).toHaveText('Melee');
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await studio.close(); }
});
