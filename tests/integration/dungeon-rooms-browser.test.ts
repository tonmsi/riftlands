import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startWorldStudio } from '../../scripts/world-studio-server';
import { newWorldDocument } from '../../shared/world-schema';
import { newDungeonInterior } from '../../shared/warps';
import { newDungeonDraft, compileDungeonDraft, compactDungeonDraft, parseDungeonDraft } from '../../shared/dungeon-draft';
import { buildDungeonBundle } from '../../shared/dungeon-install';
import { BOSS_TEMPLATES } from '../../shared/boss-templates';

test('room brushes reshape masks without overlap and room passage authoring retains key and direction controls', { timeout: 60_000 }, async () => {
  const dir = await mkdtemp(join(tmpdir(), 'riftlands-room-editor-'));
  const options = { root: resolve('.'), documentPath: join(dir, 'world.json'), dungeonPath: join(dir, 'dungeons.json'), dataPath: join(dir, 'accounts.json'), port: 0 };
  const draft = newDungeonDraft(); draft.id = 'room-test'; draft.origin = { x: 0, y: 0 };
  draft.tiles[3 * draft.width] = 'path';
  draft.entities = [{ id: 'boss', kind: 'boss', template: BOSS_TEMPLATES[0].id, label: 'Boss', x: 18, y: 12, level: 1, radius: 36 }];
  draft.rooms = [{ id: 'a', name: 'Biblioteca', tiles: [] }, { id: 'b', name: 'Tesoro', tiles: [] }];
  for (let y = 3; y <= 7; y++) for (let x = 3; x <= 7; x++) if (x <= 5 || y >= 6) draft.rooms[0].tiles.push({ x, y });
  for (let y = 3; y <= 7; y++) for (let x = 10; x <= 14; x++) draft.rooms[1].tiles.push({ x, y });
  const bundle = buildDungeonBundle(draft, [], { checkPlacement: false }), project = newWorldDocument(); project.interiors = [newDungeonInterior('crypt', bundle.definition)];
  await writeFile(options.documentPath, JSON.stringify(project)); await writeFile(options.dungeonPath, JSON.stringify([{ ...bundle, draft: compactDungeonDraft(draft) }]));
  const studio = await startWorldStudio(options); let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    const response = await fetch(new URL('/__world/project', studio.url));
    assert.equal(response.ok, true, await response.text());
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } }), errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(d => localStorage.setItem('riftlands.dungeon-draft.v2', JSON.stringify(d)), draft);
    await page.goto(studio.url.replace('world-maker.html', 'dungeon-maker.html'));
    await expect(page.locator('#dungeon-room-list option')).toHaveCount(2);
    await page.locator('#dungeon-room-list').selectOption('a');
    const box = (await page.locator('#map').boundingBox())!, scale = Math.max(4, Math.min(46, (box.width - 60) / 24, (box.height - 60) / 18));
    const tile = async (x: number, y: number) => page.mouse.click(box.x + (box.width - 24 * scale) / 2 + (x + .5) * scale, box.y + (box.height - 18 * scale) / 2 + (y + .5) * scale);
    await page.locator('[data-tool="room-cut"]').click(); await tile(3,3);
    const stored = () => page.evaluate(() => localStorage.getItem('riftlands.dungeon-draft.v2')!);
    assert.equal(parseDungeonDraft(await stored()).rooms![0].tiles.some(p => p.x === 3 && p.y === 3), false);
    await page.locator('[data-tool="room-add"]').click(); await tile(3,3);
    assert.equal(parseDungeonDraft(await stored()).rooms![0].tiles.some(p => p.x === 3 && p.y === 3), true);
    await tile(10,4); assert.equal(parseDungeonDraft(await stored()).rooms![0].tiles.some(p => p.x === 10 && p.y === 4), false);
    await page.locator('#dungeon-room-connect').click(); const frame = page.frameLocator('#dungeon-passages-frame');
    await expect(frame.locator('#warp-room')).toHaveValue('room-test:a', { timeout: 20_000 });
    await expect(frame.locator('#warp-destination')).toHaveValue('crypt');
    await frame.locator('#warp-tool').click();
    const frameBox = (await frame.locator('#map').boundingBox())!;
    await page.mouse.click(frameBox.x + frameBox.width / 2 + 24, frameBox.y + frameBox.height / 2 + 24);
    await frame.locator('#warp-room').selectOption('room-test:b');
    await page.mouse.click(frameBox.x + frameBox.width / 2 + 24, frameBox.y + frameBox.height / 2 + 24);
    await expect(frame.locator('#warp-name')).toHaveValue(/Biblioteca → Tesoro$/);
    await frame.locator('#warp-entry-size').selectOption('3,1');
    await frame.locator('#warp-arrival-size').selectOption('1,2');
    await expect(frame.locator('#warp-entry-size')).toHaveValue('3,1');
    await expect(frame.locator('#warp-arrival-size')).toHaveValue('1,2');
    await frame.locator('#warp-requires-key').check(); await expect(frame.locator('#warp-key-place')).toBeVisible();
    await frame.locator('#warp-one-way').check(); await frame.locator('#warp-update').click();
    await expect(frame.locator('#warp-one-way')).toBeChecked();
    await page.locator('#close-passages').click();
    await page.locator('#add-encounter').click();
    await page.locator('[data-tool="encounter-rectangle"]').click();
    await page.locator('#fit').click();
    const fresh=(await page.locator('#map').boundingBox())!, rs=Math.max(4,Math.min(46,(fresh.width-60)/24,(fresh.height-60)/18));
    const point=(x:number,y:number)=>({x:fresh.x+(fresh.width-24*rs)/2+(x+.5)*rs,y:fresh.y+(fresh.height-18*rs)/2+(y+.5)*rs});
    const a=point(2,2), b=point(6,6);
    await page.mouse.move(a.x,a.y);await page.mouse.down();await page.mouse.move(b.x,b.y,{steps:4});await page.mouse.up();
    assert.equal(parseDungeonDraft(await stored()).encounters.at(-1)!.tiles!.length,25);
    await page.locator('[data-tool="encounter-cut"]').click();const cut=point(4,4);await page.mouse.click(cut.x,cut.y);
    assert.equal(parseDungeonDraft(await stored()).encounters.at(-1)!.tiles!.length,24);
    const empty=parseDungeonDraft(await stored());empty.encounters=[];empty.entities=[];
    await page.addInitScript(d=>localStorage.setItem('riftlands.dungeon-draft.v2',JSON.stringify(d)),empty);
    await page.reload();
    await expect(page.locator('#encounter option')).toHaveCount(0);
    await expect(page.locator('#compile')).toBeEnabled();
    await expect(page.locator('[data-tool="encounter-rectangle"]')).toBeDisabled();
    await page.locator('#add-encounter').click();await expect(page.locator('#encounter option')).toHaveCount(1);
    await page.locator('#remove-encounter').click();await expect(page.locator('#encounter option')).toHaveCount(0);
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await studio.close(); await rm(dir, { recursive: true, force: true }); }
});
